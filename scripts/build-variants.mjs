// Build the static GitHub Pages data bundle from independently editable variants.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=rel=>JSON.parse(fs.readFileSync(path.join(root,rel),'utf8'));
const metadata=read('data/metadata.json');
const variants={};
const schemes={};
for(let i=1;i<=20;i++){
  const key=String(i).padStart(2,'0');
  const entry=read('data/variants/'+key+'.json');
  if(!entry.variant||!entry.scheme ||
    !['task4','task5','task6'].every(t=>entry.scheme[t])){
    throw new Error('Invalid or incomplete source for variant '+key);
  }
  variants[key]=entry.variant;
  schemes[key]=entry.scheme;
}
const output=`/* Generated from data/variants/*.json by scripts/build-variants.mjs.
   Edit the JSON sources and regenerate; do not edit this file by hand. */
window.SITEMATH_DATA = ${JSON.stringify({...metadata,variants})};
window.SITEMATH_SCHEMES = ${JSON.stringify(schemes)};
`;
const target=path.join(root,'variants.js');
if(process.argv.includes('--check')){
  if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output){
    process.stderr.write('variants.js differs from data/variants sources. Run node scripts/build-variants.mjs\\n');
    process.exit(1);
  }
  console.log('All 20 variant JSON sources match the published bundle.');
}else{
  fs.writeFileSync(target,output);
  console.log('Built variants.js for '+Object.keys(variants).length+' variants.');
}
